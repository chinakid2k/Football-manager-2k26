// Helper function to calculate position category
function getPositionCategory(positions) {
    if (positions.includes('GK')) return 'GK';
    if (positions.some(p => ['CB', 'LB', 'RB', 'LWB', 'RWB'].includes(p))) return 'DEF';
    if (positions.some(p => ['CM', 'DM', 'AM', 'LM', 'RM'].includes(p))) return 'MID';
    if (positions.some(p => ['ST', 'CF', 'LW', 'RW'].includes(p))) return 'ATT';
    return 'MID';
}

